const LanguageContext = createContext(null);

export function translate(text, language, values={}) {
  const translated = language==='pt-BR' ? portuguese[text] ?? text : text;
  return translated.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ''));
}

export function translateKnownNote(note, language) {
  const ideaNotes = [
    'Quiero descubrir un lugar para mi próxima etapa',
    'Me importa tener más espacio para mi rutina',
    'Busco un espacio que se adapte a mi rutina',
    'Quiero conocer otros barrios de la ciudad',
    'Quiero seguir descubriendo qué me gusta',
  ];
  const original = ideaNotes.find(key => key===note || portuguese[key]===note);
  return original ? translate(original, language) : note;
}

export function roomCount(count, language) {
  if (count == null) return language==='pt-BR' ? 'Quartos a confirmar' : 'Recámaras a confirmar';
  return `${count} ${language==='pt-BR' ? (count===1?'quarto':'quartos') : (count===1?'recámara':'recámaras')}`;
}

export function bathCount(count, language) {
  if (count == null) return language==='pt-BR' ? 'Banheiros a confirmar' : 'Baños a confirmar';
  return `${count} ${language==='pt-BR' ? (count===1?'banheiro':'banheiros') : (count===1?'baño':'baños')}`;
}

export function listingReason(home, language) {
  if (home.size<20) return language==='pt-BR' ? `${roomCount(home.beds,language)} · Área a confirmar` : home.reason;
  return language==='pt-BR' ? `${roomCount(home.beds,language)} · ${home.size} m² anunciados` : home.reason;
}

function initialLanguage() {
  try { return localStorage.getItem('inmuebles24-v2-language')==='pt-BR' ? 'pt-BR' : 'es-MX'; }
  catch { return 'es-MX'; }
}

function initialCurrency() {
  try { return localStorage.getItem('inmuebles24-v2-currency')==='USD' ? 'USD' : 'MXN'; }
  catch { return 'MXN'; }
}

export function LanguageProvider({children}) {
  const [language,setLanguage]=useState(initialLanguage);
  const [currency,setCurrency]=useState(initialCurrency);
  useEffect(()=>{
    document.documentElement.lang=language;
    document.title=language==='pt-BR'?'Inmuebles24 · Sua busca, com você':'Inmuebles24 · Tu búsqueda, contigo';
    try { localStorage.setItem('inmuebles24-v2-language',language); } catch { /* Browsers may block storage. */ }
  },[language]);
  useEffect(()=>{try { localStorage.setItem('inmuebles24-v2-currency',currency); } catch { /* Browsers may block storage. */ }},[currency]);
  const value=useMemo(()=>({language,setLanguage,currency,setCurrency,money:amount=>formatMoney(amount,currency),compactMoney:amount=>formatCompactMoney(amount,currency),t:(text,values)=>translate(text,language,values)}),[language,currency]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context=useContext(LanguageContext);
  if (!context) throw new Error('LanguageProvider is required');
  return context;
}
